import {readdirSync, readFileSync, mkdirSync, writeFileSync, unlinkSync} from 'node:fs';
import {dirname, join, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {spawnSync} from 'node:child_process';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const samplesRoot = join(root, 'docs/samples');

function markdownFiles(directory) {
  return readdirSync(directory, {withFileTypes: true}).flatMap(entry => {
    const path = join(directory, entry.name);
    return entry.isDirectory() ? markdownFiles(path) : path.endsWith('.md') ? [path] : [];
  });
}

// Extract the displayed source, not a separately maintained copy. Every C# block
// must declare whether it is compiled or an intentionally incomplete fragment.
export function extractSamples(markdown, source) {
  const result = [];
  let blocks = 0;
  // Fail closed for alternate Markdown fences rather than silently letting
  // displayed C# bypass classification and compilation.
  for (const opening of markdown.matchAll(/^[ \t]*(?:`{3,}|~{3,})[ \t]*csharp\b[^\r\n]*/gm)) {
    if (!/^```csharp\b/.test(opening[0])) {
      const line = markdown.slice(0, opening.index).split('\n').length;
      throw new Error(`${source}:${line}: unsupported C# fence; use unindented triple backticks immediately followed by csharp`);
    }
  }
  const fences = /^```csharp([^\r\n]*)\r?\n([\s\S]*?)^```\s*$/gm;
  for (const match of markdown.matchAll(fences)) {
    blocks++;
    const line = markdown.slice(0, match.index).split('\n').length + 1;
    const sample = /\bsample="([^"]+)"/.exec(match[1])?.[1];
    if (!sample) {
      if (!match[1].includes('title="Illustrative fragment"')) {
        throw new Error(`${source}:${line}: classify C# as a sample or illustrative fragment`);
      }
      continue;
    }
    if (!/^[A-Za-z][A-Za-z0-9]*\/[A-Za-z][A-Za-z0-9]*\.cs$/.test(sample)) {
      throw new Error(`${source}:${line}: invalid sample path ${sample}`);
    }
    result.push({sample, code: match[2], source, line});
  }
  if (blocks !== [...markdown.matchAll(/^```csharp\b/gm)].length) {
    throw new Error(`${source}: unterminated C# fence`);
  }
  return result;
}

export function checkSamples() {
  const projects = readdirSync(samplesRoot, {withFileTypes: true})
    .filter(entry => entry.isDirectory())
    .map(entry => entry.name);
  const examples = new Map();
  for (const source of [join(root, 'README.md'), ...markdownFiles(join(root, 'docs/docs'))]) {
    for (const example of extractSamples(readFileSync(source, 'utf8'), source)) {
      if (examples.has(example.sample)) throw new Error(`Duplicate sample: ${example.sample}`);
      if (!projects.includes(example.sample.split('/')[0])) {
        throw new Error(`No project for sample: ${example.sample}`);
      }
      examples.set(example.sample, example);
    }
  }
  if (![...examples.values()].some(example => example.source === join(root, 'README.md'))) {
    throw new Error('README.md must contain a compiled quick-start example');
  }

  for (const project of projects) {
    const selected = [...examples.values()].filter(example => example.sample.startsWith(`${project}/`));
    if (!selected.length) throw new Error(`No documentation samples found for ${project}`);
    // Only delete generated .cs files in this known project's obj/Examples directory.
    const output = join(samplesRoot, project, 'obj/Examples');
    mkdirSync(output, {recursive: true});
    for (const file of readdirSync(output)) {
      if (file.endsWith('.cs')) unlinkSync(join(output, file));
    }
    for (const {sample, code, source, line} of selected) {
      const filename = sample.split('/')[1];
      const sourcePath = source.replaceAll('\\', '/').replaceAll('"', '\\"');
      writeFileSync(join(output, filename), `// Generated by check-samples.mjs\n#line ${line} "${sourcePath}"\n${code}`);
    }
    const build = spawnSync('dotnet', ['build', join(samplesRoot, project, `${project}.csproj`), '-c', 'Release', '--nologo'],
      {cwd: root, stdio: 'inherit'});
    if (build.error) throw build.error;
    if (build.status !== 0) throw new Error(`Documentation sample build failed: ${project}`);
  }
  console.log(`Compiled ${examples.size} documentation blocks in ${projects.length} projects.`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) checkSamples();
